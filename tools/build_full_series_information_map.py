def volume_for(episode: int) -> tuple[int, str]:
    if episode <= 20:
        return 1, "穿越入局与医馆求生"
    if episode <= 40:
        return 2, "王府误判与密谍司围猎"
    if episode <= 60:
        return 3, "景朝暗线与陈迹设局"
    if episode <= 80:
        return 4, "修行门径与大势力升级"
    return 5, "战争权谋与阶段性终局"


def chapter_range(episode: int) -> str:
    if episode == 19:
        return "原著第41章（ID 24430699）"
    if episode == 20:
        return "原著第29-30章（ID 24430687/24430688）"
    if episode <= 20:
        return "原著楔子卷约33-36章"
    if episode <= 40:
        start = 37 + (episode - 21) * 2
        return f"原著第一卷约{start}-{start + 2}章，制作前精确对照"
    if episode <= 60:
        start = 80 + (episode - 41) * 5
        return f"原著第二至三卷约{start}-{start + 5}章，制作前精确对照"
    if episode <= 80:
        start = 194 + (episode - 61) * 5
        return f"原著第四卷约{start}-{start + 5}章，制作前精确对照"
    if episode == 81:
        return "卷五弹性入口锚：原著约299章，制作前精确对照"
    if episode == 100:
        return "卷五弹性出口锚：原著约713章，制作前精确对照"
    return "卷五弹性区间：不预分章节，待卷三数据与 Roger 总集数裁定"


def drama_type(title: str, episode: int) -> str:
    if any(word in title for word in ("剿匪", "旗", "破阵", "斩将", "城", "战前")):
        return "WAR_EPIC"
    if any(word in title for word in ("夜探", "追影", "围猎", "追踪", "敌营", "密档")):
        return "STEALTH"
    if any(word in title for word in ("反杀", "试刀", "山君", "十坎", "修行")):
        return "ACTION_CONFLICT"
    if episode % 10 in (4, 9):
        return "COURTROOM_CONFRONTATION"
    if episode % 10 in (5, 0):
        return "EMOTIONAL_RELATIONSHIP"
    if episode >= 61:
        return "POWER_ESCALATION"
    return "DIALOGUE_MYSTERY"


NARRATIVE_ENGINES = (
    "EVIDENCE_CHAIN",
    "COUNTDOWN",
    "DUAL_LINE",
    "INTERROGATION",
    "REVERSE_INFERENCE",
    "FLASHBACK_RECONSTRUCTION",
    "SIEGE_CLOCK",
    "IDENTITY_TEST",
)


def narrative_engine(episode: int) -> str:
    return NARRATIVE_ENGINES[(episode - 18) % len(NARRATIVE_ENGINES)]


def generic_nodes(episode: int, title: str, next_title: str | None) -> list[str]:
    arc = volume_for(episode)[1]
    return [
        f"“{title}”必须以一个可见事件或证据改变陈迹在“{arc}”中的处境。",
        f"陈迹验证该事件后推翻第一判断，并迫使至少一个角色或阵营重新站队。",
        (
            f"本集留下不可逆代价或新目标，把因果直接推进到“{next_title}”。"
            if next_title
            else "本集完成阶段性身份、阵营与战争结算，同时保留世界继续扩展的余波。"
        ),
    ]


def build() -> dict:
    episodes = []
    for offset, title in enumerate(TITLES):
        episode = 18 + offset
        next_title = TITLES[offset + 1] if offset + 1 < len(TITLES) else None
        previous_title = TITLES[offset - 1] if offset else "E17 重做后的密谍司证据链"
        volume, volume_title = volume_for(episode)
        nodes = CUSTOM_NODES.get(episode) or generic_nodes(episode, title, next_title)
        episodes.append(
            {
                "episode": f"E{episode:02d}" if episode < 100 else "E100",
                "title": title,
                "volume": volume,
                "volume_title": volume_title,
                "information_nodes": nodes,
                "end_hook": (
                    f"{nodes[2]} 下一集立即切入 E{episode + 1:02d}《{next_title}》。"
                    if next_title
                    else f"{nodes[2]} 以“斩将夺旗”完成当前原著进度的阶段性终局。"
                ),
                "dialogue_line_budget": {"minimum": 29, "target": 32},
                "drama_type": drama_type(title, episode),
                "narrative_engine": narrative_engine(episode),
                "layout_stage": "CONCRETE" if episode in CUSTOM_NODES else "TEMPLATE",
                "source_chapters": chapter_range(episode),
                "volume_flexibility": "FLEXIBLE_ENTRY_EXIT_ANCHORS_ONLY" if episode >= 81 else "FIXED_LAYOUT_DRAFT",
                "pending_roger_decision": (
                    {
                        "decision": "BAILI_IDENTITY_REVEAL_EPISODE",
                        "recommended_episode": "E60",
                        "status": "PENDING_ROGER"
                    }
                    if episode == 60
                    else None
                ),
                "causal_chain": {
                    "from": previous_title,
                    "current": title,
                    "to": next_title or "阶段性终局",
                },
                "review_status": "DRAFT_REQUIRES_CLAUDE_REVIEW",
                "production_allowed": False,
            }
        )
    return {
        "schema": "qingshan.full_series_information_node_map.v1",
        "authorization_ref": "ROGER-20260716-FULL-SERIES-SCRIPTS",
        "scope": "E18-E100",
        "status": "GLOBAL_LAYOUT_DRAFT_REQUIRES_CLAUDE_REVIEW",
        "episode_count": len(episodes),
        "hard_rules": {
            "information_nodes_minimum": 3,
            "dialogue_line_minimum": 29,
            "review_required_before_episode_scripts": True,
            "review_required_before_production": True,
            "pacing_profile": "v2-final+v2.1+v2.2+v2.3-frozen",
        },
        "episodes": episodes,
    }


